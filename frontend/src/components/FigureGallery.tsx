import { Box, Typography } from '@mui/material';
import { API_BASE, api } from '../services/api';
import { useApi } from '../hooks/useApi';
import Async from './Async';
import EmptyState from './EmptyState';
import Panel from './Panel';

export default function FigureGallery({ group }: { group: 'eda' | 'evaluation' }) {
  const state = useApi(() => api.figures(), []);
  const title = group === 'eda' ? 'Exploratory data analysis plots' : 'Evaluation figures';
  return (
    <Panel title={title} subtitle="Generated by python -m scripts.generate_reports. Associations shown are not causal.">
      <Async state={state}>
        {(d) => {
          const plots = d.plots.filter((p) => p.group === group);
          if (!plots.length) return <EmptyState message="No figures yet. From the backend folder run: python -m scripts.generate_reports" />;
          return (
            <Box sx={{ display: 'grid', gap: 3, gridTemplateColumns: { xs: '1fr', xl: 'repeat(2,1fr)' } }}>
              {plots.map((p) => (
                <Box key={p.file}>
                  <Box component="img" src={`${API_BASE}/report-files/${p.file}`} alt={p.title} sx={{ width: '100%', borderRadius: 2, border: '1px solid #E3E7F1' }} />
                  <Typography variant="caption" color="text.secondary">{p.caption}</Typography>
                </Box>
              ))}
            </Box>
          );
        }}
      </Async>
    </Panel>
  );
}
